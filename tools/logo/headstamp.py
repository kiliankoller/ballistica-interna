"""Draws the BallisticaInterna logo: a case head with the headstamp BALLISTICA / INTERNA, primer and rim, brass on
anthracite.

Both words are centred on one circle between primer and rim, nearer the rim as on a real headstamp: the top word
with its letters pointing outward, the bottom word pointing inward. Each letter is placed by its real advance width, measured on that
circle, so both words have the same distance to the rim, the same distance to the primer and the same letter
spacing. The letters are written as outlines, so the SVG needs no font.

  pip install fonttools
  python3 tools/logo/headstamp.py <BarlowSemiCondensed-Bold.ttf>

Font: Barlow Semi Condensed Bold (SIL Open Font License), github.com/google/fonts/tree/main/ofl/barlowsemicondensed.
Writes apps/desktop/src/renderer/src/assets/logo.svg (512 × 512, full bleed) and apps/desktop/build/icon.svg
(1024 × 1024 with the margin of the macOS icon grid); render build/icon.png from the latter (see README.md here).
"""
import math
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
TOP, BOTTOM = 'BALLISTICA', 'INTERNA'
SIZE = 66          # font size: the longer word spans about 170 degrees
TRACKING = 8       # letter spacing on the text circle
C = 256            # centre of the 512 drawing
R_HEAD = 186
R_RING = 176       # ring near the rim (stroke 6, inner edge 173)
R_TEXT = 130       # centre line of the letters
R_PRIMER = 60
BRASS, BRASS_LIGHT, BRASS_DARK, ANTHRACITE = '#b8862e', '#e0b968', '#7e5a1c', '#2a2e33'


def word(font, text, rm, top):
    upm = font['head'].unitsPerEm
    cap = font['OS/2'].sCapHeight
    s = SIZE / upm
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    letters = []
    for ch in text:
        g = gs[cmap[ord(ch)]]
        pen = SVGPathPen(gs)
        g.draw(pen)
        letters.append((g.width, pen.getCommands()))
    # angle of each letter on the text circle: advance plus tracking
    widths = [(w * s + TRACKING) / rm for w, _ in letters]
    total = sum(widths) - TRACKING / rm
    direction = 1 if top else -1  # top clockwise, bottom counter-clockwise: both read left to right
    theta = (-math.pi / 2 if top else math.pi / 2) - direction * total / 2
    out = []
    for (w, d), aw in zip(letters, widths):
        tc = theta + direction * (aw - TRACKING / rm) / 2
        x, y = C + rm * math.cos(tc), C + rm * math.sin(tc)
        phi = math.degrees(tc) + (90 if top else -90)
        out.append(f'<path transform="translate({x:.2f} {y:.2f}) rotate({phi:.2f}) scale({s:.5f} {-s:.5f}) '
                   f'translate({-w / 2:.1f} {-cap / 2:.1f})" d="{d}"/>')
        theta += direction * aw
    return out


def drawing(font):
    letters = word(font, TOP, R_TEXT, True) + word(font, BOTTOM, R_TEXT, False)
    return '\n'.join([
        f'<rect width="512" height="512" rx="112" fill="{ANTHRACITE}"/>',
        f'<circle cx="{C}" cy="{C}" r="{R_HEAD}" fill="{BRASS}"/>',
        f'<circle cx="{C}" cy="{C}" r="{R_HEAD}" fill="none" stroke="{BRASS_LIGHT}" stroke-width="4" opacity=".7"/>',
        f'<circle cx="{C}" cy="{C}" r="{R_RING}" fill="none" stroke="{BRASS_DARK}" stroke-width="6"/>',
        f'<circle cx="{C}" cy="{C}" r="{R_PRIMER}" fill="{BRASS_DARK}"/>',
        f'<circle cx="{C}" cy="{C}" r="48" fill="{BRASS_LIGHT}"/>',
        f'<circle cx="{C}" cy="{C}" r="12" fill="{BRASS}"/>',
        f'<g fill="{ANTHRACITE}">', *letters, '</g>',
    ])


def main():
    font = TTFont(sys.argv[1])
    body = drawing(font)
    head = '<!-- generated by tools/logo/headstamp.py; letters: Barlow Semi Condensed Bold, SIL Open Font License -->'
    logo = ROOT / 'apps/desktop/src/renderer/src/assets/logo.svg'
    logo.parent.mkdir(parents=True, exist_ok=True)
    logo.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">{head}\n{body}\n</svg>\n')
    # macOS icon grid: 824 of 1024 px, centred; Windows and Linux use the same image
    icon = ROOT / 'apps/desktop/build/icon.svg'
    icon.parent.mkdir(parents=True, exist_ok=True)
    icon.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">{head}\n'
                    f'<g transform="translate(100 100) scale({824 / 512})">\n{body}\n</g>\n</svg>\n')
    print(logo.relative_to(ROOT), icon.relative_to(ROOT))


if __name__ == '__main__':
    main()
